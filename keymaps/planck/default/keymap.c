bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  switch (keycode) {
    case PAREN:
      if (record->event.pressed) {
        if (keyboard_report->mods & MOD_BIT(KC_LSFT) || keyboard_report->mods & MOD_BIT(KC_RSFT)){
          clear_mods();
          register_code(KC_LSFT);
          register_code(KC_0);
        } else {
          register_code(KC_LSFT);
          register_code(KC_9);
        }
        clear_keyboard();
      }
      return false;
      break;
    case BRACK:
      if (record->event.pressed) {
        if (keyboard_report->mods & MOD_BIT(KC_LSFT) || keyboard_report->mods & MOD_BIT(KC_RSFT)){
          clear_mods();
          register_code(KC_LSFT);
          register_code(KC_RBRACKET);
        } else {
          register_code(KC_LSFT);
          register_code(KC_LBRACKET);
        }
        clear_keyboard();
      }
      return false;
      break;
    case ANGLE:
      if (record->event.pressed) {
        if (keyboard_report->mods & MOD_BIT(KC_LSFT) || keyboard_report->mods & MOD_BIT(KC_RSFT)){
          clear_mods();
          register_code(KC_LSFT);
          register_code(KC_DOT);
        } else {
          register_code(KC_LSFT);
          register_code(KC_COMMA);
        }
        clear_keyboard();
      }
      return false;
      break;
    case SQUARE:
      if (record->event.pressed) {
        if (keyboard_report->mods & MOD_BIT(KC_LSFT) || keyboard_report->mods & MOD_BIT(KC_RSFT)){
          clear_mods();
          register_code(KC_RBRACKET);
        } else {
          register_code(KC_LBRACKET);
        }
        clear_keyboard();
      }
      return false;
      break;
    case DOT:
      if (record->event.pressed) {
        if (keyboard_report->mods & MOD_BIT(KC_LSFT) || keyboard_report->mods & MOD_BIT(KC_RSFT)){
          clear_mods();
          register_code(KC_DOT);
        } else {
          register_code(KC_COMMA);
        }
        clear_keyboard();
      }
      return false;
      break;
  }
  return true;
}
